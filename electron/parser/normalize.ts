/**
 * Нормализация значений для поиска и сопоставления. См. ARCHITECTURE.md §6.
 *
 * Границы слова здесь намеренно не через \b: в JavaScript он работает только
 * по ASCII и после кириллицы молча не срабатывает.
 */

/** Латинские гомоглифы к кириллице: «ВВГ» латиницей и кириллицей — одно слово. */
const HOMOGLYPHS: Record<string, string> = {
  a: 'а', e: 'е', o: 'о', p: 'р', c: 'с', y: 'у', x: 'х',
  k: 'к', b: 'в', h: 'н', m: 'м', t: 'т',
}

/**
 * Нормализованное название товара.
 *
 *   «Кабель ВВГнг(А)-LS 3х2,5»  ->  «кабель ввгнг а ls 3x2.5»
 *   «АЛЬФА-ЛИПОЕВАЯ К-ТА 60МГ»  ->  «альфа липоевая к та 60мг»
 */
export function normalizeName(input: string): string {
  let s = String(input ?? '').toLowerCase().replace(/ё/g, 'е')

  // Гомоглифы применяем только к отдельно стоящим латинским буквам внутри
  // кириллических слов; чистая латынь (LS, SOLGAR) остаётся собой.
  s = s.replace(/[а-я]+[a-z]+|[a-z]+[а-я]+/g, (mixed) =>
    mixed.replace(/[a-z]/g, (ch) => HOMOGLYPHS[ch] ?? ch),
  )

  s = s
    .replace(/(\d)[\s  ](?=\d{3}(?!\d))/g, '$1') // 1 158 -> 1158
    .replace(/(?<=\d),(?=\d)/g, '.')                       // 3,5 -> 3.5
    .replace(/(\d)\s*[x×*х]\s*(?=\d)/gi, '$1x')            // 3 х 2,5 -> 3x2.5
    // Число и единицу склеиваем: в прайсах пишут «100мг», а пользователь
    // наберёт «100 мг» — без склейки запрос распадётся на два токена, и
    // одинокого «мг» в индексе не окажется.
    .replace(/(\d)\s+(мг|мкг|мкме|ме|мл|гр|кг|[глм])(?![а-яa-z0-9])/gi, '$1$2')
    .replace(/№\s*/g, '№')
    .replace(/[^\wа-я0-9№.%]+/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim()

  return s
}

/** Артикул: только буквы и цифры, верхний регистр. «ВВГ-3х2.5» и «ВВГ 3Х2,5» совпадут. */
export function normalizeArticle(input: string): string {
  return String(input ?? '').toUpperCase().replace(/[^0-9A-ZА-ЯЁ]+/g, '').replace(/Ё/g, 'Е')
}

const UNIT_ALIASES: Record<string, string> = {
  уп: 'уп', упак: 'уп', упаковка: 'уп', 'уп.': 'уп',
  шт: 'шт', 'шт.': 'шт', штука: 'шт',
  фл: 'фл', флак: 'фл', флакон: 'фл',
  амп: 'амп', ампула: 'амп',
  туб: 'туб', туба: 'туб',
  пл: 'пл', пласт: 'пл',
  кг: 'кг', г: 'г', л: 'л', мл: 'мл', м: 'м',
}

/** Единицы измерения к общему виду: упак/уп/упаковка -> уп. */
export function normalizeUnit(input: string): string {
  const s = String(input ?? '').toLowerCase().replace(/ё/g, 'е').trim()
  if (s === '') return ''
  return UNIT_ALIASES[s] ?? s
}
