-- Вторая цена прайса.
--
-- В прайсах цена почти никогда не одна: у «Прима Интернэшнл» это «Наличный» и
-- «Безналичный», у «Медлайф» — три уровня. Раньше выигрывала одна колонка, а
-- остальные уезжали в extra_json — там они видны в карточке, но по ним нельзя
-- ни сравнить поставщиков, ни отфильтровать.
--
-- Подпись храним рядом со значением и берём из шапки прайса: «Безналичный»
-- говорит покупателю больше, чем «вторая цена», а придумать общее название для
-- всех поставщиков всё равно нельзя.
--
-- В price_history вторая цена не пишется: история строится вокруг основной
-- цены, и удвоение таблицы ради справочной колонки не окупается.
